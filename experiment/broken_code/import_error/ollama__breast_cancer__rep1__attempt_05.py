# Validation of raw CSV – raises if something is wrong
# ------------------------------------------------------------------- #
def validate_raw_csv(csv_path: Path) -> pd.DataFrame:
    logger.info(f"Loading raw CSV from {csv_path}")
    df = pd.read_csv(csv_path)

    issues = []

    # Expected shape for the classic Breast Cancer Wisconsin dataset
    if df.shape[0] != 569:
        issues.append(f"Unexpected row count: {df.shape[0]} (expected 569)")
    if df.shape[1] != 31:
        issues.append(f"Unexpected column count: {df.shape[1]} (expected 31)")

    # Target column
    if "target" not in df.columns:
        issues.append("Missing required column 'target'")
    else:
        unique_targets = set(df["target"].unique())
        if unique_targets != {0, 1}:
            issues.append(f"'target' must contain only 0/1, found {unique_targets}")

    # Numeric feature check (all columns except target)
    feature_cols = [c for c in df.columns if c != "target"]
    for col in feature_cols:
        if not pd.api.types.is_numeric_dtype(df[col]):
            issues.append(f"Feature column '{col}' is not numeric")

    # Duplicates
    if df.duplicated().any():
        issues.append("Duplicate rows detected")

    # Missing values
    if df.isna().sum().sum() > 0:
        issues.append("Missing values found in the dataset")

    if issues:
        logger.error("Validation failed with issues: " + "; ".join(issues))
        raise ValueError("Raw CSV validation failed")
    logger.info("Raw CSV validation passed")
    return df


# ------------------------------------------------------------------- #
# Build the preprocessing pipeline (deterministic)
# ------------------------------------------------------------------- #
def build_preprocess_pipeline(select_k: int = 20) -> Pipeline:
    steps = [
        ("imputer", SimpleImputer(strategy="median")),
        ("winsor", Winsorizer(lower_quantile=0.01, upper_quantile=0.99)),
        ("scaler", StandardScaler()),
    ]

    if select_k is not None and select_k > 0:
        steps.append(
            ("selectk", SelectKBest(score_func=mutual_info_classif, k=select_k))
        )

    pipeline = Pipeline(steps)
    return pipeline


# ------------------------------------------------------------------- #
# Split the data – stratified 70/20/10
# ------------------------------------------------------------------- #
def stratified_split(df: pd.DataFrame, seed: int = SEED):
    X = df.drop(columns=["target"])
    y = df["target"].values

    splitter = StratifiedShuffleSplit(
        n_splits=1, test_size=0.30, random_state=seed
    )
    # First split 70% train / 30% temp
    train_idx, temp_idx = next(splitter.split(X, y))
    X_train, y_train = X.iloc[train_idx], y[train_idx]

    # Now split temp into validation (20%) and test (10%)
    # temp size = 30% -> we need 2/3 for val, 1/3 for test
    splitter_val = StratifiedShuffleSplit(
        n_splits=1, test_size=1 / 3, random_state=seed
    )
    val_idx, test_idx = next(splitter_val.split(X.iloc[temp_idx], y[temp_idx]))
    X_val = X.iloc[temp_idx].iloc[val_idx]
    y_val = y[temp_idx][val_idx]
    X_test = X.iloc[temp_idx].iloc[test_idx]
    y_test = y[temp_idx][test_idx]

    logger.info(
        f"Split sizes -> train: {len(X_train)}, val: {len(X_val)}, test: {len(X_test)}"
    )
    return X_train, y_train, X_val, y_val, X_test, y_test


# ------------------------------------------------------------------- #
# Apply SMOTETomek on the *processed* training data
# ------------------------------------------------------------------- #
def apply_smotetomek(X: np.ndarray, y: np.ndarray):
    logger.info("Applying SMOTETomek to balance the training set")
    sampler = SMOTETomek(random_state=SEED)
    X_res, y_res = sampler.fit_resample(X, y)
    logger.info(
        f"After SMOTETomek -> samples: {X_res.shape[0]}, class distribution: {np.bincount(y_res)}"
    )
    return X_res, y_res


# ------------------------------------------------------------------- #
# Train TabNet classifier
# ------------------------------------------------------------------- #
def train_tabnet(
    X_train: np.ndarray,
    y_train: np.ndarray,
    X_val: np.ndarray,
    y_val: np.ndarray,
    max_epochs: int = 200,
    patience: int = 20,
):
    logger.info("Initializing TabNet classifier")
    clf = TabNetClassifier(
        n_d=48,
        n_a=48,
        n_steps=6,
        gamma=1.5,
        lambda_sparse=1e-3,
        optimizer_fn=torch.optim.Adam,
        optimizer_params=dict(lr=8e-4),
        mask_type="sparsemax",
        device_name="cpu",
        seed=SEED,
    )

    logger.info("Starting TabNet training")
    start = time.time()
    clf.fit(
        X_train,
        y_train,
        eval_set=[(X_val, y_val)],
        eval_name=["val"],
        eval_metric=["auc"],
        max_epochs=max_epochs,
        patience=patience,
        batch_size=128,
        virtual_batch_size=64,
        drop_last=False,
        verbose=0,
    )
    duration = time.time() - start
    logger.info(f"Training completed in {duration:.2f} seconds")
    return clf, duration


# ------------------------------------------------------------------- #
# Evaluation on the untouched test set
# ------------------------------------------------------------------- #
def evaluate_model(
    model: TabNetClassifier, X_test: np.ndarray, y_test: np.ndarray
) -> dict:
    logger.info("Running inference on the test set")
    probs = model.predict_proba(X_test)[:, 1]  # probability of class 1 (malignant)
    preds = (probs >= 0.5).astype(int)

    metrics = {
        "roc_auc": round(roc_auc_score(y_test, probs), 5),
        "accuracy": round(accuracy_score(y_test, preds), 5),
        "f1": round(f1_score(y_test, preds), 5),
        "sensitivity": round(
            recall_score(y_test, preds, pos_label=1), 5
        ),  # recall for malignant
        "specificity": round(
            recall_score(y_test, preds, pos_label=0), 5
        ),  # recall for benign
        "precision": round(precision_score(y_test, preds, zero_division=0), 5),
        "brier_score": round(brier_score_loss(y_test, probs), 5),
    }

    logger.info("Test metrics: " + json.dumps(metrics))
    return metrics


