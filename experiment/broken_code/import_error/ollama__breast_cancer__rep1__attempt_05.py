def predict_single(sample_dict: dict) -> dict:
    """
    Accepts a dictionary of feature_name -> value (must contain all features
    exactly as in the original CSV) and returns the malignant probability.
    """
    pipeline, model = load_artifacts()

    # Preserve column order
    feature_names = pipeline.named_steps["imputer"].feature_names_in_
    df = pd.DataFrame([sample_dict], columns=feature_names)

    # Transform
    X_processed = pipeline.transform(df)

    # Torch tensor
    tensor = torch.from_numpy(X_processed.astype(np.float32))

    with torch.no_grad():
        prob = model.predict_proba(tensor.numpy())[:, 1].item()

    label = "malignant" if prob >= 0.5 else "benign"
    return {"malignant_probability": round(prob, 5), "prediction": label}


